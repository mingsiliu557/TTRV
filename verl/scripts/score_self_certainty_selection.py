def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    score_parser = subparsers.add_parser("score")
    score_parser.add_argument("--benchmarks", nargs="+", choices=BENCHMARK_ORDER, required=True)
    score_parser.add_argument("--output-dir", type=Path, required=True)
    score_parser.add_argument("--model", type=Path, default=MODEL_PATH)
    score_parser.add_argument("--open-ours", type=Path, default=OPEN_OURS_PATH)
    score_parser.add_argument("--device", default="cuda:0")
    score_parser.add_argument("--candidate-batch-size", type=int, default=8)
    score_parser.add_argument("--limit-per-benchmark", type=int, default=0)
    score_parser.add_argument("--no-flash-attn", action="store_true")

    aggregate_parser = subparsers.add_parser("aggregate")
    aggregate_parser.add_argument("--input-dir", type=Path, required=True)
    aggregate_parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()

    if args.command == "aggregate":
        aggregate(args.input_dir, args.output_dir)
        return 0

    if args.candidate_batch_size <= 0:
        raise ValueError("candidate batch size must be positive")
    open_ours = load_open_ours(args.open_ours)
    model, tokenizer, processor = load_model(args.model, args.device, not args.no_flash_attn)
    print(f"[self-certainty] model_loaded device={args.device} benchmarks={','.join(args.benchmarks)}", flush=True)
    summaries = []
    for benchmark in args.benchmarks:
        summaries.append(
            process_benchmark(
                benchmark,
                args.output_dir,
                model,
                tokenizer,
                processor,
                args.device,
                args.candidate_batch_size,
                args.limit_per_benchmark,
                open_ours,
            )
        )
    atomic_json(args.output_dir / f"worker_summary_{args.device.replace(':', '_')}.json", summaries)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
