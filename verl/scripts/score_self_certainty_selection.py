def read_jsonl(path: Path) -> Iterable[dict[str, Any]]:
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSON at {path}:{line_number}") from exc
            if not isinstance(row, dict):
                raise ValueError(f"Expected object at {path}:{line_number}")
            yield row


def append_jsonl(path: Path, row: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(dict(row), ensure_ascii=False, allow_nan=False) + "\n")
        handle.flush()
        os.fsync(handle.fileno())


def atomic_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".partial")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    os.replace(temporary, path)


def atomic_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        raise ValueError(f"Refusing to write empty CSV: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".partial")
    with temporary.open("w", encoding="utf-8", newline="") as handle:
        fieldnames = list(dict.fromkeys(key for row in rows for key in row))
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    os.replace(temporary, path)


def canonical_prediction(value: Any, is_valid: bool) -> str:
    # This is the existing all-output majority@32 convention: every invalid
    # response belongs to one ordinary `unknown` category and remains eligible.
    if not is_valid:
        return "unknown"
    text = str(value).strip()
    return text if text else "unknown"


def load_open_ours(path: Path) -> dict[tuple[str, str], dict[str, Any]]:
    rows: dict[tuple[str, str], dict[str, Any]] = {}
    for row in read_jsonl(path):
        key = (str(row["benchmark"]), str(row["question_id"]))
        if key in rows:
            raise ValueError(f"Duplicate open Ours-Selection key: {key}")
        rows[key] = row
    return rows


def load_groups(benchmark: str, spec: Mapping[str, Any], open_ours: Mapping[tuple[str, str], dict[str, Any]]):
    if spec["group"] == "closed":
        result = []
        for row in read_jsonl(Path(spec["source"])):
            samples = []
            for sample in row["samples"]:
                prediction = canonical_prediction(sample.get("prediction"), sample.get("prediction") != "unknown")
                samples.append(
                    {
                        "sample_idx": int(sample["sample_index"]),
                        "raw_text": str(sample["response_raw"]),
                        "prediction": prediction,
                        "is_valid": prediction != "unknown",
                        "is_correct": bool(sample["correct"]),
                        "response_token_len": int(sample["response_token_len"]),
                    }
                )
            result.append(
                {
                    "benchmark": benchmark,
                    "question_id": str(row["index"]),
                    "prompt": str(row["prompt"]),
                    "ground_truth": row["ground_truth"],
                    "parquet_key": str(row["index"]),
                    "samples": samples,
                    "majority_answer": canonical_prediction(
                        row["majority_prediction"], row["majority_prediction"] != "unknown"
                    ),
                    "majority_correct": bool(row["majority_correct"]),
                    "ours_answer": canonical_prediction(
                        row["reward_selection_prediction"], row["reward_selection_prediction"] != "unknown"
                    ),
                    "ours_correct": bool(row["reward_selection_correct"]),
                    "ours_source": "saved_full_validation_reward_selection32",
                }
            )
        return result

    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in read_jsonl(Path(spec["source"])):
        grouped[str(row["question_id"])].append(row)
    result = []
    for qid, records in grouped.items():
        records.sort(key=lambda item: int(item["sample_idx"]))
        samples = [
            {
                "sample_idx": int(record["sample_idx"]),
                "raw_text": str(record["raw_text"]),
                "prediction": canonical_prediction(record["parsed_answer"], bool(record["is_valid"])),
                "is_valid": bool(record["is_valid"]),
                "is_correct": bool(record["is_correct"]),
                "response_token_len": int(record["response_token_len"]),
            }
            for record in records
        ]
        counter = Counter(sample["prediction"] for sample in samples)
        majority_answer = counter.most_common(1)[0][0]
        majority_idx = next(i for i, sample in enumerate(samples) if sample["prediction"] == majority_answer)
        ours = open_ours.get((benchmark, qid))
        if ours is None:
            raise KeyError(f"Missing open Ours-Selection reference for {benchmark}/{qid}")
        if str(ours["string_majority_answer"]) != majority_answer:
            raise ValueError(f"Majority drift for {benchmark}/{qid}")
        result.append(
            {
                "benchmark": benchmark,
                "question_id": qid,
                "prompt": str(records[0]["prompt"]),
                "ground_truth": records[0]["ground_truth"],
                "parquet_key": qid,
                "samples": samples,
                "majority_answer": majority_answer,
                "majority_correct": bool(samples[majority_idx]["is_correct"]),
                "ours_answer": str(ours["ours_answer"]),
                "ours_correct": bool(ours["ours_correct"]),
                "ours_source": str(ours["reward_variant"]),
            }
        )
    result.sort(key=lambda item: int(next(r["subset_position"] for r in grouped[item["question_id"]])))
    return result


def load_parquet_rows(path: Path, group_kind: str) -> dict[str, dict[str, Any]]:
    import pyarrow.parquet as pq

    rows: dict[str, dict[str, Any]] = {}
    for position, row in enumerate(pq.read_table(path).to_pylist()):
        extra = row.get("extra_info") or {}
        if group_kind == "closed":
            key = str(extra.get("index") or f"__row_{position}")
        else:
            key = str(extra.get("diagnostic_question_id") or "")
        if not key:
            raise ValueError(f"Missing parquet key at {path} row {position}")
        if key in rows:
            raise ValueError(f"Duplicate parquet key {key} in {path}")
        rows[key] = row
    return rows


def load_model(model_path: Path, device: str, use_flash_attn: bool):
    import torch
    from transformers import AutoModel, AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(model_path, trust_remote_code=True, use_fast=False)
    processor = hf_processor(str(model_path), trust_remote_code=True)
    if processor is None:
        raise RuntimeError(f"No multimodal processor for {model_path}")
    model = AutoModel.from_pretrained(
        model_path,
        trust_remote_code=True,
        torch_dtype=torch.bfloat16,
        low_cpu_mem_usage=True,
        use_flash_attn=use_flash_attn,
    )
    model.img_context_token_id = tokenizer.convert_tokens_to_ids("<IMG_CONTEXT>")
    model.eval().to(device)
    if not hasattr(model.language_model, "model") or not hasattr(model.language_model, "lm_head"):
        raise TypeError("Expected a causal LM with `.model` and `.lm_head`")
    return model, tokenizer, processor


def repeat_cache(cache: Any, batch_size: int):
    from transformers.cache_utils import DynamicCache

    legacy = cache.to_legacy_cache() if hasattr(cache, "to_legacy_cache") else cache
    repeated = tuple(
        tuple(tensor.repeat_interleave(batch_size, dim=0) for tensor in layer)
        for layer in legacy
    )
    return DynamicCache.from_legacy_cache(repeated)


def self_certainty_from_logits(logits: Any) -> Any:
    # KL(U || p) = logsumexp(logits) - mean(logits) - log(V).
    # This is algebraically identical to -log(V) - mean(log_softmax(logits)).
    values = logits.float()
    vocab_size = values.shape[-1]
    return torch_logsumexp(values) - values.mean(dim=-1) - math.log(vocab_size)


def torch_logsumexp(values: Any) -> Any:
    import torch

    return torch.logsumexp(values, dim=-1)


def score_responses(
    model: Any,
    tokenizer: Any,
    processor: Any,
    parquet_row: Mapping[str, Any],
    saved_prompt: str,
    samples: Sequence[Mapping[str, Any]],
    device: str,
    candidate_batch_size: int,
) -> tuple[list[float], list[int], dict[str, Any]]:
    import torch

    prepared, _ = _prepare_inputs(processor, parquet_row)
    reconstructed_ids = prepared["input_ids"]
    prompt_ids = tokenizer(saved_prompt, add_special_tokens=False, return_tensors="pt")["input_ids"]
    if reconstructed_ids.shape != prompt_ids.shape or not torch.equal(reconstructed_ids, prompt_ids):
        raise ValueError(
            f"Saved prompt token mismatch: reconstructed={tuple(reconstructed_ids.shape)} "
            f"saved={tuple(prompt_ids.shape)}"
        )
    response_ids: list[list[int]] = []
    saved_response_lengths: list[int] = []
    response_length_drifts: list[int] = []
    for sample in samples:
        ids = tokenizer.encode(str(sample["raw_text"]), add_special_tokens=False)
        saved_length = int(sample["response_token_len"])
        response_ids.append([int(value) for value in ids])
        saved_response_lengths.append(saved_length)
        response_length_drifts.append(len(ids) - saved_length)
    if len(response_ids) != EXPECTED_SAMPLES:
        raise ValueError(f"Expected {EXPECTED_SAMPLES} candidates, got {len(response_ids)}")

    prompt_ids = prompt_ids.to(device)
    prompt_mask = torch.ones_like(prompt_ids)
    pixel_values = prepared["pixel_values"].to(device=device, dtype=torch.bfloat16)
    lm = model.language_model
    with torch.inference_mode(), torch.autocast(device_type="cuda", dtype=torch.bfloat16):
        visual = model.extract_feature(pixel_values)
        prompt_embeds = lm.get_input_embeddings()(prompt_ids).clone()
        image_positions = prompt_ids.eq(model.img_context_token_id)
        visual_flat = visual.reshape(-1, visual.shape[-1])
        if int(image_positions.sum().item()) != int(visual_flat.shape[0]):
            raise ValueError(
                f"Visual-token mismatch: prompt={int(image_positions.sum())} encoder={visual_flat.shape[0]}"
            )
        prompt_embeds[image_positions] = visual_flat.to(prompt_embeds.dtype)
        prefill = lm.model(
            inputs_embeds=prompt_embeds,
            attention_mask=prompt_mask,
            use_cache=True,
            return_dict=True,
        )
        first_logits = lm.lm_head(prefill.last_hidden_state[:, -1, :])
        first_score = float(self_certainty_from_logits(first_logits)[0].item())

    scores = [float("-inf")] * len(response_ids)
    for start in range(0, len(response_ids), candidate_batch_size):
        stop = min(start + candidate_batch_size, len(response_ids))
        chunk = response_ids[start:stop]
        nonempty = [index for index, ids in enumerate(chunk) if ids]
        if not nonempty:
            continue
        tails = [chunk[index][:-1] for index in nonempty]
        max_tail = max(len(ids) for ids in tails)
        if max_tail == 0:
            for index in nonempty:
                scores[start + index] = first_score
            continue
        pad_id = tokenizer.pad_token_id
        if pad_id is None:
            pad_id = tokenizer.eos_token_id
        tail_ids = torch.full((len(nonempty), max_tail), int(pad_id), dtype=torch.long, device=device)
        tail_mask = torch.zeros((len(nonempty), max_tail), dtype=prompt_mask.dtype, device=device)
        for row_index, ids in enumerate(tails):
            if ids:
                tail_ids[row_index, : len(ids)] = torch.tensor(ids, dtype=torch.long, device=device)
                tail_mask[row_index, : len(ids)] = 1
        full_mask = torch.cat(
            [prompt_mask.expand(len(nonempty), -1), tail_mask],
            dim=1,
        )
        chunk_cache = repeat_cache(prefill.past_key_values, len(nonempty))
        with torch.inference_mode(), torch.autocast(device_type="cuda", dtype=torch.bfloat16):
            tail_output = lm.model(
                input_ids=tail_ids,
                attention_mask=full_mask,
                past_key_values=chunk_cache,
                use_cache=False,
                return_dict=True,
            )
            tail_logits = lm.lm_head(tail_output.last_hidden_state)
            tail_scores = self_certainty_from_logits(tail_logits).detach().cpu()
        for row_index, chunk_index in enumerate(nonempty):
            token_count = len(chunk[chunk_index])
            tail_count = token_count - 1
            total = first_score + float(tail_scores[row_index, :tail_count].sum().item())
            scores[start + chunk_index] = total / token_count
        del chunk_cache, tail_output, tail_logits, tail_scores
    if not any(math.isfinite(value) for value in scores):
        raise ValueError("All candidates have empty response-token sequences")
    return scores, [len(ids) for ids in response_ids], {
        "prompt_token_len": int(prompt_ids.shape[1]),
        "image_context_token_count": int(prompt_ids.eq(model.img_context_token_id).sum().item()),
        "image_tile_count": int(pixel_values.shape[0]),
        "vocab_size": int(lm.lm_head.weight.shape[0]),
        "first_position_self_certainty": first_score,
        "candidate_saved_response_token_lens": saved_response_lengths,
        "retokenized_length_mismatch_count": sum(value != 0 for value in response_length_drifts),
        "retokenized_length_drift_max_abs": max(abs(value) for value in response_length_drifts),
    }


def process_benchmark(
    benchmark: str,
    output_dir: Path,
    model: Any,
    tokenizer: Any,
    processor: Any,
    device: str,
    candidate_batch_size: int,
    limit: int,
    open_ours: Mapping[tuple[str, str], dict[str, Any]],
) -> dict[str, Any]:
    spec = SPECS[benchmark]
    groups = load_groups(benchmark, spec, open_ours)
    expected = int(spec["expected"])
    if len(groups) != expected:
        raise ValueError(f"{benchmark}: expected {expected} groups, got {len(groups)}")
    if limit > 0:
        groups = groups[:limit]
    parquet_rows = load_parquet_rows(Path(spec["parquet"]), str(spec["group"]))
    destination = output_dir / benchmark / "question_scores.jsonl"
    completed = {str(row["question_id"]) for row in read_jsonl(destination)} if destination.exists() else set()
    for position, group in enumerate(groups, start=1):
        qid = str(group["question_id"])
        if qid in completed:
            continue
        parquet_key = str(group["parquet_key"])
        if parquet_key not in parquet_rows:
            raise KeyError(f"{benchmark}/{qid}: parquet key {parquet_key!r} not found")
        scores, token_counts, audit = score_responses(
            model,
            tokenizer,
            processor,
            parquet_rows[parquet_key],
            str(group["prompt"]),
            group["samples"],
            device,
            candidate_batch_size,
        )
        selected_index = int(np.argmax(np.asarray(scores, dtype=np.float64)))
        selected = group["samples"][selected_index]
        max_score = float(scores[selected_index])
        tie_count = sum(abs(value - max_score) <= 1e-8 for value in scores if math.isfinite(value))
        row = {
            "benchmark": benchmark,
            "benchmark_group": str(spec["group"]),
            "question_id": qid,
            "sample_count": len(group["samples"]),
            "ground_truth": group["ground_truth"],
            "majority_answer": group["majority_answer"],
            "majority_correct": bool(group["majority_correct"]),
            "ours_answer": group["ours_answer"],
            "ours_correct": bool(group["ours_correct"]),
            "ours_source": group["ours_source"],
            "self_certainty_sample_index": selected_index,
            "self_certainty_answer": selected["prediction"],
            "self_certainty_correct": bool(selected["is_correct"]),
            "self_certainty_is_valid": bool(selected["is_valid"]),
            "self_certainty_score": max_score,
            "self_certainty_tie_count": tie_count,
            "self_certainty_response_raw": selected["raw_text"],
            "self_certainty_response_token_len": token_counts[selected_index],
            "candidate_self_certainty": scores,
            "candidate_response_token_lens": token_counts,
            "invalid_policy": "invalid candidates remain eligible; selected invalid is incorrect",
            "logit_temperature": 1.0,
            "score_formula": "mean_response_token_KL_uniform_to_raw_model_distribution",
            **audit,
        }
        append_jsonl(destination, row)
        completed.add(qid)
        if position % 10 == 0 or position == len(groups):
            print(f"[self-certainty] {benchmark} {position}/{len(groups)}", flush=True)
    rows = list(read_jsonl(destination))
    target = len(groups)
    if len(rows) != target:
        raise ValueError(f"{benchmark}: expected {target} output rows, got {len(rows)}")
    summary = {
        "benchmark": benchmark,
        "benchmark_group": str(spec["group"]),
        "questions": len(rows),
        "majority_correct": sum(bool(row["majority_correct"]) for row in rows),
        "ours_correct": sum(bool(row["ours_correct"]) for row in rows),
        "self_certainty_correct": sum(bool(row["self_certainty_correct"]) for row in rows),
        "self_certainty_invalid_selected": sum(not bool(row["self_certainty_is_valid"]) for row in rows),
        "source": str(spec["source"]),
        "parquet": str(spec["parquet"]),
        "limit": limit,
    }
    atomic_json(output_dir / benchmark / "summary.json", summary)
    return summary


def aggregate(input_dir: Path, output_dir: Path) -> None:
    rows = []
    for benchmark in BENCHMARK_ORDER:
        path = input_dir / benchmark / "summary.json"
        if not path.is_file():
            raise FileNotFoundError(path)
        row = json.loads(path.read_text(encoding="utf-8"))
        n = int(row["questions"])
        rows.append(
            {
                "benchmark": benchmark,
                "group": row["benchmark_group"],
                "n": n,
                "majority_correct": int(row["majority_correct"]),
                "majority_at_32": int(row["majority_correct"]) / n,
                "ours_correct": int(row["ours_correct"]),
                "ours_selection_at_32": int(row["ours_correct"]) / n,
                "self_certainty_correct": int(row["self_certainty_correct"]),
                "self_certainty_at_32": int(row["self_certainty_correct"]) / n,
                "self_certainty_invalid_selected": int(row["self_certainty_invalid_selected"]),
            }
        )

    def group_summary(label: str, members: Sequence[str]) -> dict[str, Any]:
        selected = [row for row in rows if row["benchmark"] in members]
        n = sum(int(row["n"]) for row in selected)
        return {
            "benchmark": label,
            "group": "summary",
            "n": n,
            "majority_correct": sum(int(row["majority_correct"]) for row in selected),
            "majority_at_32": sum(int(row["majority_correct"]) for row in selected) / n,
            "ours_correct": sum(int(row["ours_correct"]) for row in selected),
            "ours_selection_at_32": sum(int(row["ours_correct"]) for row in selected) / n,
            "self_certainty_correct": sum(int(row["self_certainty_correct"]) for row in selected),
            "self_certainty_at_32": sum(int(row["self_certainty_correct"]) for row in selected) / n,
            "self_certainty_invalid_selected": sum(int(row["self_certainty_invalid_selected"]) for row in selected),
            "dataset_macro_majority_at_32": float(np.mean([row["majority_at_32"] for row in selected])),
            "dataset_macro_ours_selection_at_32": float(np.mean([row["ours_selection_at_32"] for row in selected])),
            "dataset_macro_self_certainty_at_32": float(np.mean([row["self_certainty_at_32"] for row in selected])),
        }

    summaries = [
        group_summary("CLOSED_MICRO", CLOSED_ORDER),
        group_summary("OPEN_MICRO", OPEN_ORDER),
        group_summary("ALL_MICRO", BENCHMARK_ORDER),
    ]
    output_dir.mkdir(parents=True, exist_ok=True)
